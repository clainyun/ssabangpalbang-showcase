-- 3) 반영 결과 검증.
--
-- 아파트 원본 데이터는 마이그레이션이 아니라 별도 적재로 들어오므로, 빈 DB(신규 환경·CI)
-- 에서는 JOIN 대상이 없어 반영 건수가 0이 된다. 따라서 절대 개수가 아니라 "대상 단지가
-- 존재하는 만큼 정확히 반영됐는가"라는 상대 정합성으로 검증한다
-- (V27__publish_transparent_apartment_images.sql 과 같은 방식).
DO $$
DECLARE
    expected_v3 BIGINT;
    actual_v3 BIGINT;
    expected_new BIGINT;
    actual_new BIGINT;
BEGIN
    SELECT count(*) INTO expected_v3
    FROM apartment
    WHERE complex_code IN (SELECT complex_code FROM republished_codes);

    SELECT count(*) INTO actual_v3
    FROM apartment_image ai
    JOIN apartment a ON a.id = ai.apartment_id
    WHERE a.complex_code IN (SELECT complex_code FROM republished_codes)
      AND ai.object_key LIKE 'apartment-images/v3/%';

    IF actual_v3 <> expected_v3 THEN
        RAISE EXCEPTION
            'Expected % republished v3 apartment images, found %',
            expected_v3, actual_v3;
    END IF;

    SELECT count(*) INTO expected_new
    FROM apartment
    WHERE complex_code IN (SELECT complex_code FROM newly_registered_codes);

    SELECT count(*) INTO actual_new
    FROM apartment_image ai
    JOIN apartment a ON a.id = ai.apartment_id
    WHERE a.complex_code IN (SELECT complex_code FROM newly_registered_codes);

    IF actual_new <> expected_new THEN
        RAISE EXCEPTION
            'Expected % newly registered apartment images, found %',
            expected_new, actual_new;
    END IF;
END
$$;
